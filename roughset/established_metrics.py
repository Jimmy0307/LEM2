"""Established evaluation helpers used by the research branch.

Variation Ratio follows Gal (2016, Sec. 3.3.1, Eq. 3.19), which attributes the
categorical dispersion measure to Freeman (1965):

    VR(x) = 1 - f_x / T

where f_x is the modal-label frequency across T predictions.

Reference:
    Gal, Y. (2016). Uncertainty in Deep Learning. PhD thesis,
    University of Cambridge.
    https://www.cs.ox.ac.uk/people/yarin.gal/website/thesis/thesis.pdf
"""

from __future__ import annotations

from collections import Counter
from typing import Any, Mapping, Optional, Sequence, Set, TYPE_CHECKING

import numpy as np
import pandas as pd

from .evaluation import predict_table
from .federated import _client_orderings, union_rules

if TYPE_CHECKING:
    from .core import Rule


def variation_ratio_by_case(predictions_by_order: Sequence[Sequence[Any]]) -> np.ndarray:
    """Return Gal/Freeman Variation Ratio for every test case.

    The input is interpreted as a matrix with shape
    ``(number_of_orderings, number_of_test_cases)``. For test case ``x``:

        VR(x) = 1 - f_x / T

    where ``T`` is the number of client-order predictions and ``f_x`` is the
    frequency of the modal predicted class. A value of 0 means complete
    agreement across orders; larger values indicate less consensus.

    Citation: Gal (2016), Sec. 3.3.1, Eq. (3.19), citing Freeman (1965).
    """
    matrix = np.asarray(predictions_by_order, dtype=object)
    if matrix.size == 0:
        return np.asarray([], dtype=float)
    if matrix.ndim != 2:
        raise ValueError("predictions_by_order must be a 2-D order-by-case matrix")

    n_orders = matrix.shape[0]
    if n_orders == 0:
        return np.asarray([], dtype=float)

    ratios = []
    for case_idx in range(matrix.shape[1]):
        counts = Counter(matrix[:, case_idx].tolist())
        modal_frequency = max(counts.values()) if counts else 0
        ratios.append(1.0 - (modal_frequency / n_orders))
    return np.asarray(ratios, dtype=float)


def mean_variation_ratio(predictions_by_order: Sequence[Sequence[Any]]) -> float:
    """Arithmetic mean of per-case Variation Ratios (descriptive summary)."""
    ratios = variation_ratio_by_case(predictions_by_order)
    return float(ratios.mean()) if ratios.size else float("nan")


def audit_order_variation_ratio(
    test: pd.DataFrame,
    local_rules: Mapping[str, Sequence["Rule"]],
    default_class: Any,
    prediction_policy: str,
    rule_weights: Optional[Mapping[Any, float]] = None,
    rule_support_sets: Optional[Mapping[Any, Set[Any]]] = None,
    class_sizes: Optional[Mapping[Any, int]] = None,
    conflict_case_flags: Optional[Sequence[bool]] = None,
    max_permutations: int = 120,
    seed: int = 42,
) -> dict[str, Any]:
    """Measure client-order predictive disagreement with Variation Ratio.

    Client orders are generated by the same ordering routine as the frozen
    FIRST_MATCH robustness audit. No local rules are relearned. Each ordering
    only changes the traversal order of the same learned local rule sets.

    Returns per-case Variation Ratios, the arithmetic mean over all test cases,
    and—when policy-independent conflict flags are supplied—the same mean
    restricted to the established Lindgren-style conflict set.
    """
    orders = _client_orderings(
        list(local_rules),
        max_permutations=max_permutations,
        seed=seed,
    )

    if not orders or len(test) == 0:
        return {
            "orderings_checked": len(orders),
            "variation_ratio_by_case": tuple(),
            "mean_variation_ratio": float("nan"),
            "mean_variation_ratio_conflict": float("nan"),
        }

    predictions_by_order: list[list[str]] = []
    for order in orders:
        ordered_local = {name: local_rules[name] for name in order}
        ordered_global_rules = union_rules(ordered_local)
        predictions, _matched = predict_table(
            test,
            ordered_global_rules,
            default_class,
            prediction_policy=prediction_policy,
            rule_weights=rule_weights,
            rule_support_sets=rule_support_sets,
            class_sizes=class_sizes,
        )
        predictions_by_order.append([str(value) for value in predictions])

    ratios = variation_ratio_by_case(predictions_by_order)
    mean_all = float(ratios.mean()) if ratios.size else float("nan")

    mean_conflict = float("nan")
    if conflict_case_flags is not None:
        conflict_mask = np.asarray(conflict_case_flags, dtype=bool)
        if len(conflict_mask) != len(ratios):
            raise ValueError("conflict_case_flags length must equal number of test cases")
        if conflict_mask.any():
            mean_conflict = float(ratios[conflict_mask].mean())

    return {
        "orderings_checked": len(orders),
        "variation_ratio_by_case": tuple(float(value) for value in ratios.tolist()),
        "mean_variation_ratio": mean_all,
        "mean_variation_ratio_conflict": mean_conflict,
    }
